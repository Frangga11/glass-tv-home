package com.gathin.tvhome;

import java.io.File;
import java.io.FileInputStream;
import java.io.IOException;
import java.util.Locale;

/** Shared allowlist and path policy for files received by the local QR upload endpoints. */
final class UploadFilePolicy {
    enum ImageFormat {
        JPEG("image/jpeg", "jpg"),
        PNG("image/png", "png"),
        WEBP("image/webp", "webp"),
        GIF("image/gif", "gif");

        final String mimeType;
        final String extension;

        ImageFormat(String mimeType, String extension) {
            this.mimeType = mimeType;
            this.extension = extension;
        }
    }

    private UploadFilePolicy() {}

    /** Detects the actual container signature; filenames and client MIME are never trusted. */
    static ImageFormat detectImageFormat(File file) throws IOException {
        if (file == null || !file.isFile() || file.length() < 3) return null;
        byte[] header = new byte[12];
        int offset = 0;
        try (FileInputStream input = new FileInputStream(file)) {
            while (offset < header.length) {
                int count = input.read(header, offset, header.length - offset);
                if (count < 0) break;
                if (count == 0) continue;
                offset += count;
            }
        }
        if (offset >= 3 && unsigned(header[0]) == 0xFF
                && unsigned(header[1]) == 0xD8 && unsigned(header[2]) == 0xFF) {
            return ImageFormat.JPEG;
        }
        if (offset >= 8 && unsigned(header[0]) == 0x89 && header[1] == 'P'
                && header[2] == 'N' && header[3] == 'G'
                && header[4] == 0x0D && header[5] == 0x0A
                && header[6] == 0x1A && header[7] == 0x0A) {
            return ImageFormat.PNG;
        }
        if (offset >= 12 && header[0] == 'R' && header[1] == 'I'
                && header[2] == 'F' && header[3] == 'F'
                && header[8] == 'W' && header[9] == 'E'
                && header[10] == 'B' && header[11] == 'P') {
            return ImageFormat.WEBP;
        }
        if (offset >= 6 && header[0] == 'G' && header[1] == 'I'
                && header[2] == 'F' && header[3] == '8'
                && (header[4] == '7' || header[4] == '9') && header[5] == 'a') {
            return ImageFormat.GIF;
        }
        return null;
    }

    /**
     * Accepts an absent or generic browser MIME, otherwise requires one declared
     * Content-Type to agree with the detected image signature.
     */
    static boolean hasCompatibleContentType(String[] headerLines, ImageFormat format) {
        if (format == null) return false;
        int count = 0;
        String declared = null;
        if (headerLines != null) {
            for (String line : headerLines) {
                if (line == null) continue;
                int separator = line.indexOf(':');
                if (separator <= 0 || !"content-type".equals(
                        line.substring(0, separator).trim().toLowerCase(Locale.ROOT))) continue;
                count++;
                if (count > 1) return false;
                String value = line.substring(separator + 1).trim();
                int parameter = value.indexOf(';');
                declared = (parameter >= 0 ? value.substring(0, parameter) : value)
                        .trim().toLowerCase(Locale.ROOT);
            }
        }
        if (count == 0) return true;
        if (declared == null || declared.isEmpty()) return false;
        if ("application/octet-stream".equals(declared)) return true;
        if ("image/jpg".equals(declared) || "image/pjpeg".equals(declared)) {
            declared = "image/jpeg";
        }
        return format.mimeType.equals(declared);
    }

    static boolean isValidWallpaperImageDimensions(int width, int height) {
        return width > 0 && height > 0 && width <= 16384 && height <= 16384
                && (long) width * (long) height <= 100_000_000L;
    }

    /** Stored names are generated by the app and must remain a single safe path component. */
    static boolean isSafeStoredImageName(String name) {
        if (name == null || name.length() < 5 || name.length() > 100
                || name.startsWith(".") || name.contains("..")
                || name.indexOf('/') >= 0 || name.indexOf('\\') >= 0) return false;
        if (!name.matches("[A-Za-z0-9][A-Za-z0-9_-]{0,79}\\.[A-Za-z0-9]{2,5}")) return false;
        String extension = name.substring(name.lastIndexOf('.') + 1).toLowerCase(Locale.ROOT);
        return "jpg".equals(extension) || "jpeg".equals(extension)
                || "png".equals(extension) || "webp".equals(extension) || "gif".equals(extension);
    }

    /** Resolve only a direct, canonical child of the intended managed directory. */
    static File resolveDirectChild(File directory, String name) {
        if (directory == null || !isSafeStoredImageName(name)) return null;
        try {
            File root = directory.getCanonicalFile();
            File candidate = new File(root, name).getCanonicalFile();
            if (!root.equals(candidate.getParentFile()) || !candidate.isFile()) return null;
            return candidate;
        } catch (IOException | SecurityException ignored) {
            return null;
        }
    }

    private static int unsigned(byte value) {
        return value & 0xFF;
    }
}
